-- LuftBase 0.1.0a113 - publicacoes: formato do conteudo (MARKDOWN/HTML) e imagens do editor rico.
--
-- Equivale a migracao Alembic 20261021_0018. Execute com um usuario DONO das tabelas do schema core
-- (ex.: luft_web_owner), DEPOIS de 20261015_tb_sistema_categorias.sql (o carimbo da revisao so avanca nessa ordem).
--
--   * Aditivo: uma coluna com padrao 'MARKDOWN' (o conteudo atual continua valendo) e uma tabela nova.
--     Versoes anteriores do LuftBase ignoram os dois e continuam funcionando.
--   * Repetivel: IF NOT EXISTS e constraints protegidas; rodar duas vezes nao faz mal.
--   * Em uma transacao: se algo falhar, nada e aplicado.
--   * Carimba a revisao 20261021_0018 SO se o core estiver na 20261015_0017, para o `banco atualizar`
--     do Workspace nao tentar aplicar de novo.
--
-- Confira o resultado nas consultas do fim.

BEGIN;

ALTER TABLE core.tb_publicacao ADD COLUMN IF NOT EXISTS formato_conteudo varchar(10) NOT NULL DEFAULT 'MARKDOWN';

DO $$
BEGIN
    IF NOT EXISTS (
        SELECT 1 FROM pg_constraint
        WHERE conname = 'ck_core_publicacao_formato' AND conrelid = 'core.tb_publicacao'::regclass
    ) THEN
        ALTER TABLE core.tb_publicacao ADD CONSTRAINT ck_core_publicacao_formato
            CHECK (formato_conteudo IN ('MARKDOWN', 'HTML'));
    END IF;
END $$;

CREATE TABLE IF NOT EXISTS core.tb_publicacaoimagem (
    id_imagem     bigint GENERATED BY DEFAULT AS IDENTITY NOT NULL,
    id_publicacao bigint,
    tipo_mime     varchar(50)  NOT NULL,
    nome_arquivo  varchar(255),
    tamanho       integer      NOT NULL,
    hash_sha256   varchar(64)  NOT NULL,
    dados         bytea        NOT NULL,
    criado_por    varchar(150) NOT NULL,
    data_criacao  timestamp(3) without time zone NOT NULL DEFAULT (CURRENT_TIMESTAMP AT TIME ZONE 'America/Sao_Paulo'),
    CONSTRAINT pk_core_publicacaoimagem PRIMARY KEY (id_imagem),
    CONSTRAINT fk_core_publicacaoimagem_publicacao FOREIGN KEY (id_publicacao)
        REFERENCES core.tb_publicacao (id_publicacao) ON DELETE CASCADE,
    CONSTRAINT ck_core_publicacaoimagem_mime
        CHECK (tipo_mime IN ('image/png', 'image/jpeg', 'image/gif', 'image/webp'))
);

CREATE INDEX IF NOT EXISTS ix_core_publicacaoimagem_publicacao ON core.tb_publicacaoimagem (id_publicacao);

-- Toda aplicacao exibe publicacoes globais (e as imagens delas): o acesso vai para TODOS os papeis das apps.
DO $$
DECLARE papel text;
BEGIN
    FOR papel IN
        SELECT rolname FROM pg_catalog.pg_roles
        WHERE rolname LIKE 'luft\_%\_app' OR rolname = 'luft_core_security_admin'
    LOOP
        EXECUTE format('GRANT SELECT, INSERT, UPDATE, DELETE ON core.tb_publicacaoimagem TO %I', papel);
    END LOOP;
END $$;

UPDATE core.alembic_version SET version_num = '20261021_0018' WHERE version_num = '20261015_0017';

COMMIT;

-- Conferencia
SELECT version_num AS revisao_do_core FROM core.alembic_version;
SELECT column_name, data_type, column_default FROM information_schema.columns
WHERE table_schema = 'core' AND table_name = 'tb_publicacao' AND column_name = 'formato_conteudo';
SELECT grantee, privilege_type FROM information_schema.role_table_grants
WHERE table_schema = 'core' AND table_name = 'tb_publicacaoimagem' ORDER BY grantee, privilege_type;
