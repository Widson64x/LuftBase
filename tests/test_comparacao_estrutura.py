MODULO_BANCO = sys.modules["luftbase.cli.banco"]
AGORA = datetime(2026, 10, 15, 10, 30)
INDICE = "CREATE INDEX ix_tb_fatura_numero ON faturas.tb_fatura USING btree (numero)"


def _fatura() -> Tabela:
    tabela = Tabela("tb_fatura")
    tabela.colunas["id"] = Coluna("id", "integer", True, identidade="d")
    tabela.colunas["numero"] = Coluna("numero", "character varying(20)", True)
    tabela.colunas["valor"] = Coluna("valor", "numeric(14,2)", False, "0")
    tabela.restricoes["pk_tb_fatura"] = ("p", "PRIMARY KEY (id)")
    tabela.indices["ix_tb_fatura_numero"] = INDICE
    return tabela


def _estrutura(*tabelas: Tabela, existe: bool = True, schema: str = "faturas") -> Estrutura:
    estrutura = Estrutura(schema, existe=existe)
    estrutura.tabelas = {t.nome: t for t in tabelas}
    return estrutura


def _comparar(origem: Estrutura, destino: Estrutura, **opcoes: Any) -> Resultado:
    return comparar(origem, destino, agora=lambda: AGORA, **opcoes)


def test_estruturas_iguais_nao_geram_diferenca_nem_script() -> None:
    resultado = _comparar(_estrutura(_fatura()), _estrutura(_fatura()))

    assert resultado.iguais
    assert resultado.script == ""


def test_tabela_nova_gera_create_indices_e_grants_na_ordem_certa() -> None:
    nova = _fatura()
    nova.restricoes["fk_tb_fatura_cliente"] = (
        "f",
        "FOREIGN KEY (id) REFERENCES faturas.tb_cliente(id)",
    )

    resultado = _comparar(
        _estrutura(nova),
        _estrutura(),
        role_destino="luft_faturas_hml_app",
        role_destino_existe=True,
        nome_origem="desenvolvimento",
        nome_destino="homologacao",
    )
    sql = resultado.script

    assert sql.startswith("-- Estrutura do schema faturas: desenvolvimento -> homologacao")
    assert "2026-10-15 10:30" in sql and "REVISE" in sql
    assert 'CREATE TABLE IF NOT EXISTS "faturas"."tb_fatura"' in sql
    assert '"id" integer GENERATED BY DEFAULT AS IDENTITY' in sql
    assert '"numero" character varying(20) NOT NULL' in sql
    assert '"valor" numeric(14,2) DEFAULT 0' in sql
    assert "CREATE INDEX IF NOT EXISTS ix_tb_fatura_numero" in sql
    assert sql.index("CREATE TABLE") < sql.index("CREATE INDEX") < sql.index("FOREIGN KEY")
    assert sql.index("FOREIGN KEY") < sql.index("GRANT ALL ON ALL TABLES")
    assert '"luft_faturas_hml_app"' in sql
    assert sql.rstrip().endswith("COMMIT;")


def test_script_nunca_apaga_nem_altera_coluna() -> None:
    destino = _fatura()
    destino.colunas["extra"] = Coluna("extra", "text", False)
    origem = _fatura()
    origem.colunas["numero"] = Coluna("numero", "character varying(40)", True)

    resultado = _comparar(_estrutura(origem), _estrutura(destino))

    assert "DROP" not in resultado.script.upper()
    assert "ALTER COLUMN" not in resultado.script.upper()
    descricoes = " ".join(d.descricao for d in resultado.manuais)
    assert "tb_fatura.numero difere" in descricoes
    assert "varying(40)" in descricoes and "varying(20)" in descricoes


