def test_cli_comparar_grava_sql_e_nao_aplica_nada(
    monkeypatch: pytest.MonkeyPatch, tmp_path: Path
) -> None:
    import luftbase.infraestrutura.comparacao_estrutura as modulo
    from luftbase.cli import operador
    from luftbase.infraestrutura.cofre.credenciais import Segredo
    from luftbase.infraestrutura.provisionamento_sistema import DestinoProvisionamento

    def destino(ambiente: str, host: str) -> DestinoProvisionamento:
        return DestinoProvisionamento(ambiente, "luft", "http://v", host, 5432, "luft_web", 0)

    bancos = {
        "desenvolvimento": destino("desenvolvimento", "172.19.85.111"),
        "homologacao": destino("homologacao", "transfersql"),
    }
    monkeypatch.setattr(operador, "abrir_cliente_vault", lambda **_: object())
    monkeypatch.setattr(
        operador,
        "pedir_banco_do_ambiente",
        lambda _c, *, ambiente, **_: (bancos[ambiente], "admin", Segredo("s")),
    )

    class Conexao:
        def __enter__(self) -> Conexao:
            return self

        def __exit__(self, *_: object) -> None:
            return None

    monkeypatch.setattr(MODULO_BANCO, "_conectar_somente_leitura", lambda _s: Conexao())
    monkeypatch.setattr(modulo, "revisao_alembic", lambda _c: "20261015_0016")
    monkeypatch.setattr(modulo, "listar_schemas", lambda _c: ["faturas"])
    monkeypatch.setattr(
        modulo,
        "comparar_schemas",
        lambda *_a, **_k: [
            comparar(
                _estrutura(_fatura()),
                _estrutura(),
                nome_origem="desenvolvimento",
                nome_destino="homologacao",
            )
        ],
    )

    resultado = CliRunner().invoke(cli, ["banco", "comparar", "--saida", str(tmp_path)])

    assert resultado.exit_code == 0, resultado.output
    arquivo = tmp_path / "estrutura_faturas_desenvolvimento_para_homologacao.sql"
    assert arquivo.is_file() and "CREATE TABLE" in arquivo.read_text(encoding="utf-8")
    assert "core: desenvolvimento=20261015_0016 homologacao=20261015_0016" in resultado.output


def test_cli_comparar_recusa_origem_igual_ao_destino() -> None:
    resultado = CliRunner().invoke(
        cli, ["banco", "comparar", "--origem", "homologacao", "--destino", "homologacao"]
    )

    assert resultado.exit_code != 0
